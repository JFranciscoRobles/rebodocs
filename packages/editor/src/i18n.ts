const LOCALES: Record<string, Messages> = { es: ES, en: EN };
/** The language texts are given in when the one asked for is not known. */
const FALLBACK = 'en';
let current = 'es';
const listeners = new Set<() => void>();

/** The language of a tag like `en-US` or `es_MX`, when the interface speaks it. */
function known(locale: string): string | undefined {
  const code = locale.toLowerCase().split(/[-_]/)[0];
  return LOCALES[locale] ? locale : LOCALES[code] ? code : undefined;
}

/** The language the interface is in. */
export function getLocale(): string {
  return current;
}

/** The languages the interface speaks, each with its name in itself. */
export function locales(): { code: string; name: string }[] {
  return Object.entries(LOCALES).map(([code, messages]) => ({ code, name: messages['locale.name'] }));
}

/**
 * Sets the language of the interface: `es`, `en`, or a tag such as `en-US`.
 * One it does not speak leaves it in English. What is already on screen keeps
 * its words: whoever built it is told, through `onLocaleChange`, to build it again.
 */
export function setLocale(locale: string): void {
  const next = known(locale) ?? FALLBACK;
  if (next === current) return;
  current = next;
  for (const listener of [...listeners]) listener();
}

/** Calls `listener` whenever the language changes. Returns how to stop. */
export function onLocaleChange(listener: () => void): () => void {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

/**
 * Adds a language, or changes texts of one there is. What it leaves out is
 * said in English. Its name in the list of languages is its `locale.name`,
 * or, without one, what the browser calls it.
 */
export function addLocale(locale: string, texts: Partial<Messages>): void {
  const name = texts['locale.name'] ?? LOCALES[locale]?.['locale.name'] ?? nameOf(locale);
  LOCALES[locale] = { ...EN, ...LOCALES[locale], ...texts, 'locale.name': name };
  // The language being shown has other words now: whoever drew them is told to draw them again.
  if (locale === current) for (const listener of [...listeners]) listener();
}

/** What a language calls itself: "Français" for `fr`. Its code where the browser does not know. */
function nameOf(locale: string): string {
  try {
    const name = new Intl.DisplayNames([locale], { type: 'language' }).of(locale) ?? locale;
    return name.charAt(0).toLocaleUpperCase(locale) + name.slice(1);
  } catch {
    return locale;
  }
}

/**
 * Every text of the interface in a language, by its key: English unless
 * another is asked for. What a translation starts from, and what tells it
 * the keys there are.
 */
export function messages(locale = FALLBACK): Messages {
  return { ...(LOCALES[known(locale) ?? FALLBACK] ?? EN) };
}

/** The text for `key` in the language of the interface, with each `{name}` replaced by its value. */
export function t(key: MessageKey, values?: Record<string, string | number>): string {
  const text = (LOCALES[current] ?? EN)[key] ?? EN[key];
  return values ? text.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole)) : text;
}

/** The names Word knows the standard styles by, and the key of what each is called here. */
const STYLE_KEYS: Record<string, MessageKey> = {
  normal: 'style.normal',
  title: 'style.title',
  subtitle: 'style.subtitle',
  'heading 1': 'style.heading1',
  'heading 2': 'style.heading2',
  'heading 3': 'style.heading3',
};

/** What a paragraph style is called in the language of the interface; one of the document's own keeps its name. */
export function styleName(style: { name: string; wordName?: string }): string {
  const key = STYLE_KEYS[style.wordName?.toLowerCase() ?? ''];
  return key ? t(key) : style.name;
}
