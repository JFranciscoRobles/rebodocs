export type Text = keyof typeof EN

/** A text of this interface in the language of the editor, with each `{name}` replaced by its value. */
function text(key: Text, values?: Record<string, string | number>): string {
  // Spanish is what the keys are; any other language the library is given reads this interface in English.
  const words: string = getLocale() === 'es' ? key : EN[key]
  return values ? words.replace(/\{(\w+)\}/g, (whole, name: string) => (name in values ? String(values[name]) : whole)) : words
}

/** `text`, for a component that is drawn again when the language changes. */
export function useTexts(): typeof text {
  useSyncExternalStore(onLocaleChange, getLocale)
  return text
}
